#!/usr/bin/env python3
"""Build the printable arm: verify the design, then write STL, STEP and images.

    python cad/build.py            # verify + export everything
    python cad/build.py --check    # verification only (no files written)
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import List

from armcad.assembly import ArmAssembly
from armcad.checks import (Finding, TorqueAnalysis, check_bed_fit, check_contacts,
                           check_interference, verification_poses)
from armcad.export import StepExporter, StlExporter
from armcad.geometry import box, translation
from armcad.kinematics import JointState, TransferPlan
from armcad.layout import DEFAULT_LAYOUT
from armcad.parts import all_parts

ROOT = Path(__file__).resolve().parent.parent


def verify(assembly: ArmAssembly) -> List[Finding]:
    poses = verification_poses(assembly)
    return [*check_contacts(assembly),
            *check_interference(assembly, poses),
            *TorqueAnalysis(assembly).worst_case(poses),
            *check_bed_fit(all_parts(assembly.layout))]


def write_report(findings: List[Finding], path: Path) -> None:
    lines = ["# Design verification report", "",
             "Generated by `python cad/build.py`. Every row must pass before printing.", "",
             "| Result | Check | Detail |", "| --- | --- | --- |"]
    lines += [f"| {'PASS' if f.ok else '**FAIL**'} | {f.check} | {f.detail} |" for f in findings]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")


def render_images(assembly: ArmAssembly, directory: Path) -> None:
    from armcad.render import render  # imported lazily: only needed for images

    directory.mkdir(parents=True, exist_ok=True)
    lay = assembly.layout
    plan = TransferPlan()
    pick = plan.waypoints(assembly.kinematics, steps=12)[0]

    def truck_at(xy):
        return box((-42, 42), (-19, 19), (0, 35)).moved(translation(xy[0], xy[1], 0))

    scene = assembly.placed(pick)
    scene["payload"] = truck_at(lay.zone_a)
    render(scene, str(directory / "workcell_pick.png"), view_dir=(0.6, 1.0, -0.55))
    render(scene, str(directory / "workcell_top.png"), view_dir=(0.0, 0.001, -1.0))

    arm_only = ArmAssembly(lay, include_workcell=False)
    home = arm_only.placed(JointState())
    render(home, str(directory / "arm_home_front.png"), view_dir=(1.0, 1.0, -0.6),
           size=(1100, 1000))
    render(home, str(directory / "arm_home_rear.png"), view_dir=(-1.0, -1.2, -0.5),
           size=(1100, 1000))
    render(home, str(directory / "arm_home_side.png"), view_dir=(-1.0, 0.0, 0.0),
           size=(1100, 1000))
    tool = {name: shape for name, shape in home.items()
            if any(key in name for key in ("wrist", "grip", "finger"))}
    render(tool, str(directory / "detail_wrist_gripper.png"), view_dir=(-1.0, 0.6, -0.4),
           size=(1000, 900))
    lower = {name: shape for name, shape in home.items()
             if any(key in name for key in ("base", "turret", "shoulder"))}
    render(lower, str(directory / "detail_base_turret.png"), view_dir=(-1.0, -1.0, -0.7),
           size=(1000, 900))
    render_print_plates(directory)


def render_print_plates(directory: Path) -> None:
    """Every printed part in its print orientation, as the slicer should show it."""
    from armcad.render import render

    parts = {p.name: p for p in all_parts(DEFAULT_LAYOUT)}
    rows = {
        "print_plate_arm.png": ["base", "turret", "upper_arm", "forearm"],
        "print_plate_tool.png": ["wrist", "gripper_body", "finger_drive", "finger_idler",
                                 "fit_test_coupon", "turret_shim_1p4mm"],
    }
    for filename, names in rows.items():
        shapes, x = {}, 0.0
        for name in names:
            shape = parts[name].printable()
            shapes[name] = shape.moved(translation(x=x))
            x += shape.BoundingBox().xlen + 12.0
        render(shapes, str(directory / filename), view_dir=(1.0, 1.0, -0.8), size=(1500, 800),
               colors={name: (240, 120, 30) for name in names})


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="verify only")
    parser.add_argument("--no-images", action="store_true", help="skip the renders")
    args = parser.parse_args()

    assembly = ArmAssembly(DEFAULT_LAYOUT)
    findings = verify(assembly)
    for f in findings:
        print(f"{'PASS' if f.ok else 'FAIL'}  {f.check:48s} {f.detail}")
    failed = [f for f in findings if not f.ok]
    print(f"\n{len(findings) - len(failed)}/{len(findings)} checks passed")
    if failed:
        return 1
    if args.check:
        return 0

    write_report(findings, ROOT / "docs" / "VERIFICATION.md")
    written = StlExporter(ROOT / "print").export(all_parts(DEFAULT_LAYOUT))
    print(f"wrote {len(written)} STL files to print/")
    StepExporter(ROOT / "cad" / "arm_assembly.step").export(assembly.placed(JointState()))
    print("wrote cad/arm_assembly.step")
    if not args.no_images:
        render_images(assembly, ROOT / "docs" / "images")
        print("wrote docs/images/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
